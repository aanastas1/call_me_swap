#include "libft.h"

char	*ft_substr(char const *s, unsigned int start, size_t len)
{
	char	*buf;
	char	*base;
	size_t	s_len;

	if (!s)
		return (NULL);
	s_len = ft_strlen(s);
	if (start >= s_len)
		return (ft_strdup(""));
	if (len > s_len - start)
		len = s_len - start;
	buf = malloc(len + 1);
	if (!buf)
		return (NULL);
	base = buf;
	while (len--)
		*buf++ = s[start++];
	*buf = '\0';
	return (base);
}
